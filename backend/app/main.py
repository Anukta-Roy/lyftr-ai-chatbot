# ---------- LiteLLM Response Cache ----------

# Use LiteLLM's own in-memory cache for asynchronous completion calls.
# The cache key is generated by LiteLLM from the model and request arguments.
# It is process-local and is cleared when the backend container restarts.
litellm.enable_cache(
    type="local",
    supported_call_types=["acompletion"]
)


# ---------- Request Schema ----------

class ChatRequest(BaseModel):

    session_id: str = Field(
        min_length=1,
        max_length=128
    )

    message: str = Field(
        min_length=1,
        max_length=4000
    )

    system_prompt: Optional[str] = None

    @field_validator("message")
    @classmethod
    def message_must_not_be_blank(cls, value):

        if not value.strip():
            raise ValueError("message must not be empty")

        return value.strip()

    @field_validator("session_id")
    @classmethod
    def session_must_not_be_blank(cls, value):

        if not value.strip():
            raise ValueError("session_id must not be empty")

        return value.strip()


# ---------- Utility Functions ----------

def now_iso():

    return datetime.now(timezone.utc).isoformat()


def get_history(db, session_id):

    rows = db.execute(
        select(Message)
        .where(Message.session_id == session_id)
        .order_by(Message.id.asc())
    ).scalars().all()

    return [
        {
            "role": row.role,
            "content": row.content
        }
        for row in rows
    ]


def parse_simulation(header_value):

    result = {}

    if not header_value:
        return result

    for item in header_value.split(","):

        if "=" not in item:
            continue

        key, status = item.strip().split("=", 1)

        try:
            code = int(status)
        except ValueError:
            continue

        if code in (429, 500, 502, 503):
            result[key.strip()] = code

    return result


def usage_value(usage, field):

    value = getattr(usage, field, None) if usage else None

    return int(value or 0)


# ---------- AI Provider with Automatic Failover ----------

async def ask_provider(messages, simulated_failures):

    if not API_KEYS:

        raise HTTPException(
            status_code=503,
            detail="No API keys configured"
        )

    attempts = 0
    last_error = None

    # Try API keys sequentially.
    # If one fails, automatically try the next.

    for index, api_key in enumerate(API_KEYS, start=1):

        key_id = f"key_{index}"

        # Failure simulation for testing.

        if "*" in simulated_failures or key_id in simulated_failures:

            attempts += 1

            last_error = f"Simulated failure for {key_id}"

            print(last_error)

            continue

        try:

            print(f"Trying AI provider with {key_id}")

            completion_kwargs = {
                "model": MODEL_NAME,
                "messages": messages,
                "api_key": api_key,
                "timeout": 30
            }

            # A failover test request must exercise the provider path even if
            # an identical prompt was cached by an earlier request.
            if simulated_failures:
                completion_kwargs["cache"] = {"no-cache": True}

            response = await acompletion(**completion_kwargs)

            hidden_params = getattr(response, "_hidden_params", {}) or {}
            cache_hit = hidden_params.get("cache_hit") is True

            choice = response.choices[0]

            reply = choice.message.content

            if not isinstance(reply, str):
                reply = str(reply or "")

            usage = getattr(response, "usage", None)

            print(f"Successful response using {key_id}")

            return {
                "reply": reply,
                "model": getattr(
                    response,
                    "model",
                    None
                ) or MODEL_NAME,

                "input_tokens": usage_value(
                    usage,
                    "prompt_tokens"
                ),

                "output_tokens": usage_value(
                    usage,
                    "completion_tokens"
                ),

                "key_id": None if cache_hit else key_id,

                "fallback_attempts": 0 if cache_hit else attempts,

                "cache_hit": cache_hit
            }

        except Exception as exc:

            # Never print the actual API key.

            last_error = str(exc).replace(
                api_key,
                "[REDACTED]"
            )

            print("========== PROVIDER ERROR ==========")
            print("Provider:", key_id)
            print("Exception:", type(exc).__name__)
            print("Details:", last_error[:1000])
            print("====================================")

            attempts += 1

            continue

    raise HTTPException(
        status_code=503,
        detail=f"All providers unavailable."
    )


